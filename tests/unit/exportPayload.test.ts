// Graph on the canvas → Copy/Download. Drip unwraps `.campaign` and requires
// name + root. A campaign-less Confirm must not produce `{ root }` only.
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { buildExportPayload, exportFileName } from '../../src/designer/exportPayload';
import type { DripGraph } from '../../src/data/graphTypes';

const GRAPH: DripGraph = {
  rootId: 'n1',
  nodes: {
    n1: { id: 'n1', type: 'ENTRY_SEGMENT', label: 'Everyone', meta: '', autoGenerated: false, _config: {} },
  },
  edges: [],
};

describe('buildExportPayload', () => {
  it('builds the wrapper from graph when campaign is null, with a name', () => {
    const payload = buildExportPayload({
      campaign: null,
      graph: GRAPH,
      last: {
        blueprint: { campaignName: 'EMI on eligible purchases' },
        sendProposals: [],
      } as never,
    });
    expect(payload).not.toBeNull();
    const campaign = payload!.campaign as { name: string; issuer: string; programs: string[]; root: DripGraph };
    expect(campaign.name).toBe('EMI on eligible purchases');
    expect(campaign.root).toEqual(GRAPH);
    expect(campaign.issuer).toBe('');
    expect(campaign.programs).toEqual([]);
    expect(payload!.claim).toMatch(/draft for review/);
    expect(payload!.suggestedMessaging).toEqual([]);
  });

  it('names the campaign Untitled when the plan has no name either', () => {
    const payload = buildExportPayload({ campaign: null, graph: GRAPH, last: null });
    expect((payload!.campaign as { name: string }).name).toBe('Untitled');
  });

  it('returns null when there is no graph — and a rootId with no nodes is no graph', () => {
    expect(buildExportPayload({ campaign: null, graph: null, last: null })).toBeNull();
    expect(buildExportPayload({ campaign: null, graph: { rootId: null, nodes: {}, edges: [] } as never, last: null })).toBeNull();
    // A `rootId` pointing at nothing used to download: a file whose root does
    // not exist. "A graph on the canvas" means at least one node.
    expect(buildExportPayload({ campaign: null, graph: { rootId: 'n1', nodes: {}, edges: [] } as never, last: null })).toBeNull();
  });

  it('THE LIVE MISS: campaign null AND nothing else is ready, and it still downloads', () => {
    // The state the buttons used to grey out on: a graph on the canvas,
    // `campaign` dropped, `exportable` false, nothing generated, no templates
    // and import readiness unverified. None of those may decide whether there
    // is a file — only whether it is a good one, which the wrapper already
    // says in `importReadiness` and `claim`.
    const payload = buildExportPayload({
      campaign: null,
      graph: GRAPH,
      last: {
        exportable: false,
        designGenerated: false,
        templateChoices: [],
        importReadiness: { status: 'unverified' },
        exportBlockedReason: 'Templates are not registered.',
        sendProposals: [],
      } as never,
    });
    expect(payload, 'a graph on the canvas is a file').not.toBeNull();
    const campaign = payload!.campaign as { name: string; root: DripGraph };
    expect(campaign.root).toEqual(GRAPH);
    expect(campaign.name.length, 'Drip needs a non-empty name').toBeGreaterThan(0);
    // The readiness travels IN the file rather than gating it.
    expect(payload!.importReadiness).toEqual({ status: 'unverified' });
    expect(payload!.templateChoices).toEqual([]);
  });

  it('does not rewrite Sends, so old _config and agentMessaging survive', () => {
    // The file contract: Drip unwraps `.campaign`, old `_config` shapes are
    // fine, and no filter rows are emitted. The graph is passed through, so
    // the way to pin that is to put the awkward shapes in and require the
    // bytes back.
    const withSends: DripGraph = {
      rootId: 'n1',
      nodes: {
        n1: { id: 'n1', type: 'ENTRY_SEGMENT', label: 'Everyone', meta: '', autoGenerated: false, _config: {} },
        n2: {
          id: 'n2', type: 'SEND', label: 'Day 0', meta: '', autoGenerated: false,
          _config: { agentMessaging: { copy: 'Split this purchase.', cta: 'Convert' }, channel: 'WHATSAPP' },
        },
        n3: {
          id: 'n3', type: 'DECISION_SPLIT', label: 'What it did', meta: '', autoGenerated: false,
          _config: { source: 'Previous step outcome', customSource: 'Transaction attribute', branches: [{ id: 'bo0', label: 'Read', values: ['READ'] }] },
        },
      },
      edges: [{ id: 'e1', from: 'n1', to: 'n2' }],
    } as never;
    const out = buildExportPayload({ campaign: null, graph: withSends, last: null });
    const root = (out!.campaign as { root: DripGraph }).root;
    expect(root, 'byte-for-byte, no rewrite').toEqual(withSends);
    expect((root.nodes.n2 as { _config: { agentMessaging?: unknown } })._config.agentMessaging).toBeTruthy();
    expect((root.nodes.n3 as { _config: { source?: string } })._config.source).toBe('Previous step outcome');
    // No filter rows invented anywhere in the file.
    expect(JSON.stringify(out)).not.toMatch(/"conditions":\s*\[\s*\{/);
  });

  it('keeps an existing campaign and overlays the canvas graph', () => {
    const payload = buildExportPayload({
      campaign: {
        id: 'DRIP-001',
        name: 'Live name',
        issuer: 'IndusInd Bank (IBL)',
        programs: ['Platinum Aura'],
        goal: null,
        controlPct: 10,
        status: 'DRAFT',
        root: { rootId: null, nodes: {}, edges: [] },
      },
      graph: GRAPH,
      last: null,
    });
    const campaign = payload!.campaign as { name: string; issuer: string; root: DripGraph };
    expect(campaign.name).toBe('Live name');
    expect(campaign.issuer).toBe('IndusInd Bank (IBL)');
    expect(campaign.root).toEqual(GRAPH);
  });
});

describe('the file is named after the campaign, not its id', () => {
  // THE LEFTOVER. The download read `campaign.id ?? campaign.name`, and a
  // campaign-less Confirm synthesises `id: 'draft'` — so a manager who hit
  // Download got `draft.json`: unrecognisable in Finder and identical between
  // two runs. The id still travels INSIDE the JSON, and drip replaces it on
  // Import; it is just not what to call the file.
  const named = (name: string) => exportFileName({ campaign: { name, id: 'draft' } });

  it('uses the plan name, and never the id', () => {
    const payload = buildExportPayload({
      campaign: null,
      graph: GRAPH,
      last: { blueprint: { campaignName: 'EMI on eligible purchases' }, sendProposals: [] } as never,
    });
    expect(exportFileName(payload)).toBe('EMI-on-eligible-purchases.json');
    // And the id is still in the file for drip to replace.
    expect((payload!.campaign as { id: string }).id).toBe('draft');
  });

  it('falls back to Untitled.json, never draft.json', () => {
    const payload = buildExportPayload({ campaign: null, graph: GRAPH, last: null });
    expect(exportFileName(payload)).toBe('Untitled.json');
    // `id` is not in the fallback chain at all, which is what makes
    // `draft.json` unreachable rather than unlikely.
    expect(named('')).toBe('campaign.json');
    expect(named('   ')).toBe('campaign.json');
    expect(exportFileName(null)).toBe('campaign.json');
  });

  it('is safe for a filesystem: no slashes, no symbols, bounded', () => {
    // A slash would nest the download or break it; `₹` and `:` are the ones a
    // real campaign name actually carries.
    expect(named('EMI ₹10,000+ / Q4: push')).toBe('EMI-10-000-Q4-push.json');
    expect(named('  spaced  ')).toBe('spaced.json');
    expect(named('₹₹₹'), 'nothing nameable left').toBe('campaign.json');
    const long = named('A'.repeat(120));
    expect(long.length).toBeLessThanOrEqual(85);
    expect(long.endsWith('.json')).toBe(true);
    expect(named('Trailing-')).toBe('Trailing.json');
  });

  it('the designer uses it, rather than reaching for the id itself', () => {
    const src = readFileSync(new URL('../../src/designer/CampaignDesigner.tsx', import.meta.url), 'utf8');
    expect(src).toMatch(/a\.download = exportFileName\(exportPayload\)/);
    expect(src, 'the id must not be back in the filename').not.toMatch(/a\.download = `\$\{\(exportPayload\.campaign/);
  });
});

describe('the designer does not leave the null-guard in place', () => {
  it('Copy/Download follow a wrapper built even when campaign is missing', () => {
    const src = readFileSync(new URL('../../src/designer/CampaignDesigner.tsx', import.meta.url), 'utf8');
    expect(src).not.toMatch(/if \(!campaign\) return null;/);
    expect(src).toMatch(/buildExportPayload\(/);
    expect(src).toMatch(/disabled=\{!exportPayload\}/);
  });
});
